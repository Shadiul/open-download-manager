// Builds the two browser versions from extension/ into dist/:
//   dist/edge    + dist/open-download-manager-edge.zip     YouTube download popup included
//   dist/chrome  + dist/open-download-manager-chrome.zip   no YouTube support (Chrome Web Store rules)
// Usage: node scripts/build.mjs [edge|chrome]   (both when no target is given)
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'extension');
const dist = path.join(root, 'dist');

export const YOUTUBE_MATCHES = [
  '*://*.youtube.com/*',
  '*://youtube.com/*',
  '*://*.youtube-nocookie.com/*',
  '*://youtu.be/*'
];

const TARGETS = {
  edge: { youtube: true },
  chrome: { youtube: false }
};

export function build(target) {
  const cfg = TARGETS[target];
  if (!cfg) throw new Error(`Unknown target ${target}`);
  const out = path.join(dist, target);
  fs.rmSync(out, { recursive: true, force: true });
  fs.cpSync(src, out, { recursive: true });

  fs.writeFileSync(path.join(out, 'lib', 'build-flags.js'),
    `// Generated by scripts/build.mjs for the ${target} build.\n` +
    `export const BUILD_TARGET = '${target}';\nexport const YOUTUBE_ENABLED = ${cfg.youtube};\n`);

  const manifestPath = path.join(out, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (!cfg.youtube) {
    // Keep the page script, and with it the video button, off YouTube entirely.
    for (const cs of manifest.content_scripts) cs.exclude_matches = [...new Set([...(cs.exclude_matches || []), ...YOUTUBE_MATCHES])];
  }
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');

  const zipPath = path.join(dist, `open-download-manager-${target}.zip`);
  fs.writeFileSync(zipPath, zipDir(out));
  return { dir: out, zip: zipPath };
}

// ---- a small zip writer, so the build needs no extra packages ----

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function listFiles(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(full, base) : [path.relative(base, full).split(path.sep).join('/')];
  });
}

function zipDir(dir) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const name of listFiles(dir)) {
    const data = fs.readFileSync(path.join(dir, name));
    const packed = zlib.deflateRawSync(data);
    const nameBuf = Buffer.from(name, 'utf8');
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(8, 8); local.writeUInt32LE(0x00210000, 10); // fixed 1980-01-01 time: reproducible zips
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(packed.length, 18); local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    locals.push(local, nameBuf, packed);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10); central.writeUInt32LE(0x00210000, 12);
    central.writeUInt32LE(crc, 16); central.writeUInt32LE(packed.length, 20); central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28); central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += 30 + nameBuf.length + packed.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(centrals.length / 2, 8); end.writeUInt16LE(centrals.length / 2, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const targets = process.argv[2] ? [process.argv[2]] : Object.keys(TARGETS);
  for (const t of targets) {
    const { dir, zip } = build(t);
    console.log(`${t}: ${path.relative(root, dir)} and ${path.relative(root, zip)}`);
  }
}
